/**
 * Orchestrates what she says. Lines are generated by the AI provider when enabled and available, otherwise
 * (or on any failure) by {@link LocalDialogueGenerator}. Player messages are also interpreted for gameplay
 * effects (commands, affection requests, apologies, promises...), but those effects are decided here on the
 * server, never by the AI.
 */
public final class DialogueService {
    private DialogueService() {}

    /** She says something on her own or in reaction to an event. */
    public static void speak(GirlfriendEntity gf, DialogueTrigger trigger, Map<String, String> vars) {
        if (!(gf.level() instanceof ServerLevel level)) return;
        DialogueContext ctx = new DialogueContext(gf, null, trigger, vars);
        boolean useAi = GFConfig.AI_FOR_AMBIENT.get() && AIService.enabled() && AIService.available(gf.data().companionId);
        if (!useAi) {
            deliver(gf, LocalDialogueGenerator.line(ctx, gf.data().companionId, gf.getRandom()), emotionFor(trigger));
            return;
        }
        String cacheKey = trigger.name() + "|" + ctx.mood + "|" + ctx.stage + "|" + ctx.partOfDay + "|" + ctx.hungerWord() + "|" + ctx.energyWord() + "|" + vars;
        MinecraftServer server = level.getServer();
        sendTyping(gf);
        AIService.generate(gf.data().companionId, ctx, null, cacheKey, server::execute, result -> {
            if (gf.isRemoved()) return;
            if (result == null) deliver(gf, LocalDialogueGenerator.line(ctx, gf.data().companionId, gf.getRandom()), emotionFor(trigger));
            else deliver(gf, result.text(), result.emotion() != Emotion.NONE ? result.emotion() : emotionFor(trigger));
        });
    }

    /** The player said something to her (talk screen or chat). */
    public static void playerSays(GirlfriendEntity gf, ServerPlayer player, String message) {
        if (!(gf.level() instanceof ServerLevel level)) return;
        CompanionData d = gf.data();
        long now = level.getGameTime();
        d.history.add(true, message, now);
        gf.controller().onTalk(player);
        gf.getLookControl().setLookAt(player, 30f, 30f);

        Intent intent = IntentClassifier.classify(message);
        Map<String, String> vars = new HashMap<>();
        Intent replyIntent = applyEffects(gf, player, message, intent, vars);
        if (replyIntent == null) return; // the effect already produced speech

        DialogueContext ctx = new DialogueContext(gf, player, DialogueTrigger.REPLY, vars);
        if (!AIService.enabled() || !AIService.available(d.companionId)) {
            deliver(gf, LocalDialogueGenerator.reply(ctx, replyIntent, d.companionId, gf.getRandom()), emotionFor(replyIntent));
            return;
        }
        sendTyping(gf);
        AIService.generate(d.companionId, ctx, message, null, level.getServer()::execute, result -> {
            if (gf.isRemoved()) return;
            if (result == null) deliver(gf, LocalDialogueGenerator.reply(ctx, replyIntent, d.companionId, gf.getRandom()), emotionFor(replyIntent));
            else deliver(gf, result.text(), result.emotion() != Emotion.NONE ? result.emotion() : emotionFor(replyIntent));
        });
    }

    /**
     * Server-side consequences of what the player said. Returns the intent the reply should address,
     * or null if an action already made her respond.
     */
    private static Intent applyEffects(GirlfriendEntity gf, ServerPlayer player, String message, Intent intent, Map<String, String> vars) {
        CompanionData d = gf.data();
        var c = gf.controller();
        long day = WorldClock.day(gf.level());
        long now = gf.level().getGameTime();
        String lower = message.toLowerCase(Locale.ROOT);

        switch (intent) {
            case COMMAND -> {
                IntentClassifier.Command cmd = IntentClassifier.command(message);
                CommandMode mode = switch (cmd) {
                    case FOLLOW -> CommandMode.FOLLOW;
                    case WAIT -> CommandMode.WAIT;
                    case SIT -> CommandMode.SIT;
                    case HOME -> CommandMode.HOME;
                    case STAY_SAFE -> CommandMode.STAY_SAFE;
                    case NONE -> null;
                };
                if (mode != null) {
                    c.command(mode, player);
                    return null;
                }
            }
            case LOVE -> {
                boolean first = !d.relationship.milestones.contains("heard_love");
                c.gain("say_love", d.relationship.stage().isRomantic() ? 3f : 1.5f, 1f);
                c.feel(d.personality.shyness > 0.5f && !d.relationship.stage().isRomantic() ? Emotion.EMBARRASSMENT : Emotion.LOVE, 0.9f, 600);
                if (first) {
                    d.relationship.milestones.add("heard_love");
                    d.memory.remember(MemoryType.MILESTONE, "you told me you love me for the first time", "said_love", day, now, 1.0f);
                }
                if (d.relationship.stage().isRomantic()) c.heartParticles(4);
            }
            case COMPLIMENT -> {
                c.gain("compliment", 2f, 0.5f);
                d.mood.shiftWellbeing(3f);
                c.feel(d.personality.shyness > 0.5f ? Emotion.EMBARRASSMENT : Emotion.JOY, 0.7f, 400);
                if (d.personality.shyness > 0.5f) d.today.add(LogKey.EMBARRASSING, 1);
                if (d.personality.shyness > 0.6f) gf.playGesture(Gesture.SHY);
            }
            case APOLOGY -> {
                MemoryEntry hurt = d.memory.find(e -> e.type == MemoryType.DISAPPOINTMENT && !e.resolved && day - e.day <= 3);
                if (hurt != null) {
                    hurt.resolved = true;
                    d.memory.remember(MemoryType.RESOLVED_CONFLICT, "you apologized after " + hurt.summary.replace("you ", "you'd "), "resolved_" + hurt.detail, day, now, 0.7f);
                    c.gain("apology", 2f, 4f);
                    d.mood.shiftWellbeing(10f);
                    c.feel(Emotion.RELIEF, 0.7f, 600);
                    vars.put("resolved", "1");
                } else {
                    d.mood.shiftWellbeing(1f);
                }
            }
            case INSULT -> {
                c.lose(4f, 2f);
                d.today.add(LogKey.DISAPPOINTMENTS, 1);
                d.mood.shiftWellbeing(-8f * GFConfig.MOOD_SENSITIVITY.get().floatValue());
                c.feel(d.personality.confidence > 0.6f ? Emotion.ANNOYANCE : Emotion.SADNESS, 0.8f, 900);
                d.memory.remember(MemoryType.DISAPPOINTMENT, "you said something mean to me", "insult", day, now, 0.6f);
                gf.playGesture(Gesture.SAD);
            }
            case PROMISE -> {
                String text = message.length() > 120 ? message.substring(0, 120) + "..." : message;
                d.memory.remember(MemoryType.PROMISE, "you promised: \"" + text + "\"", "promise_" + Integer.toHexString(lower.hashCode()), day, now, 0.8f);
                c.feel(Emotion.JOY, 0.6f, 400);
            }
            case PROMISE_KEPT -> {
                MemoryEntry p = d.memory.find(e -> e.type == MemoryType.PROMISE && !e.resolved);
                if (p != null) {
                    p.resolved = true;
                    d.today.add(LogKey.PROMISES_KEPT, 1);
                    c.gain("promise_kept", 5f, 5f);
                    d.memory.remember(MemoryType.FAVORITE_ACTIVITY, "you kept your promise (" + p.summary.replace("you promised: ", "") + ")", "kept_" + p.detail, day, now, 0.8f);
                    c.feel(Emotion.JOY, 0.9f, 600);
                } else {
                    return Intent.STATEMENT;
                }
            }
            case ASK_REMEMBER -> {
                MemoryEntry m = findRelevantMemory(d, lower);
                if (m != null) {
                    vars.put("memory", m.summary);
                    m.mentioned = true;
                }
            }
            case MISS_YOU -> {
                d.needs.addAttention(6f);
                c.gain("miss_you", 1.5f, 0.5f);
                c.feel(Emotion.LOVE, 0.6f, 400);
            }
            case GOODNIGHT -> {
                if (WorldClock.isNight(gf.level()) && d.relationship.stage().isRomantic() && !gf.isSleeping()
                        && gf.interactions().findBedNear(player, 24) != null) {
                    c.requestBedtime(player);
                    return null;
                }
            }
            case YES, NO -> {
                if (d.request != null && !d.request.accepted && now - d.request.issuedTick < 2400) {
                    RequestSystem.respond(gf, player, intent == Intent.YES);
                    return null;
                }
            }
            default -> {}
        }

        AffectionAsk ask = IntentClassifier.affection(message);
        if (ask != AffectionAsk.NONE) {
            InteractionType type = switch (ask) {
                case HUG -> InteractionType.HUG;
                case KISS -> InteractionType.KISS;
                case HOLD_HANDS -> InteractionType.HOLD_HANDS;
                case CUDDLE -> InteractionType.CUDDLE;
                case NONE -> null;
            };
            if (type != null) {
                if (!d.relationship.stage().atLeast(type.stage)) return Intent.ASK_AFFECTION_TOO_SOON;
                if (gf.interactions().start(type, player, false)) return null;
                return Intent.ASK_AFFECTION_OK;
            }
        }
        if (IntentClassifier.isPersonalFact(message)) {
            String text = message.length() > 100 ? message.substring(0, 100) + "..." : message;
            d.memory.remember(MemoryType.CONVERSATION, "you told me \"" + text + "\"", "fact_" + Integer.toHexString(lower.hashCode()), day, now, 0.55f);
        }
        if (intent == Intent.COMMAND) return Intent.STATEMENT;
        return intent;
    }

    private static MemoryEntry findRelevantMemory(CompanionData d, String lower) {
        MemoryEntry best = null;
        int bestScore = 0;
        for (MemoryEntry e : d.memory.all()) {
            int score = 0;
            for (String w : lower.split("[^a-z]+")) {
                if (w.length() >= 4 && e.summary.toLowerCase(Locale.ROOT).contains(w)) score += 2;
            }
            if (lower.contains("first") && (e.type == MemoryType.FIRST_MEETING || e.type == MemoryType.MILESTONE)) score += 2;
            if (lower.contains("gift") && e.type == MemoryType.GIFT) score += 2;
            if ((lower.contains("monster") || lower.contains("save") || lower.contains("protect")) && e.type == MemoryType.PROTECTED) score += 2;
            if (score > bestScore) {
                bestScore = score;
                best = e;
            }
        }
        if (best == null) {
            var picks = d.memory.relevant(3, Long.MAX_VALUE / 2);
            for (MemoryEntry e : picks) if (e.type != MemoryType.CONVERSATION) return e;
        }
        return best;
    }

    private static void sendTyping(GirlfriendEntity gf) {
        com.aigirlfriend.network.Net.sendNear((ServerLevel) gf.level(), gf.getX(), gf.getY(), gf.getZ(), GFConfig.SPEECH_RADIUS.get(),
                new SpeechPayload(gf.getId(), "...", Emotion.NONE.ordinal(), true, 200));
    }

    /** Shows a line: speech bubble for nearby players, chat log, conversation history. */
    public static void deliver(GirlfriendEntity gf, String text, Emotion emotion) {
        if (!(gf.level() instanceof ServerLevel level) || text == null || text.isBlank()) return;
        CompanionData d = gf.data();
        d.history.add(false, text, level.getGameTime());
        if (emotion != Emotion.NONE) gf.controller().feel(emotion, 0.5f, 200);
        int duration = Math.min(240, 60 + text.length() * 2);
        double radius = GFConfig.SPEECH_RADIUS.get();
        com.aigirlfriend.network.Net.sendNear(level, gf.getX(), gf.getY(), gf.getZ(), radius,
                new SpeechPayload(gf.getId(), text, emotion.ordinal(), false, duration));
        if (!gf.isPlayingGesture() && !gf.interactions().isActive() && gf.getRandom().nextInt(3) == 0) gf.playGesture(Gesture.TALK);
        if (GFConfig.SPEECH_IN_CHAT.get()) {
            Component line = Component.literal("<").append(Component.literal(d.name).withStyle(ChatFormatting.LIGHT_PURPLE)).append("> ").append(text);
            for (ServerPlayer p : level.players()) {
                if (p.distanceToSqr(gf) <= radius * radius) p.sendSystemMessage(line);
            }
        }
    }

    private static Emotion emotionFor(DialogueTrigger t) {
        return switch (t) {
            case SCARED, ASK_PROTECTION, HURT, CRITICAL, WEATHER_THUNDER -> Emotion.FEAR;
            case PROTECTED, DANGER_OVER, FAINT_RECOVERED -> Emotion.RELIEF;
            case GIFT_LOVED, GIFT_LIKED, HAPPY, CELEBRATE, RETURN_AFTER_AWAY, REQUEST_DONE, FED -> Emotion.JOY;
            case AFFECTIONATE, MILESTONE, INITIATIVE, LEAD_TO_BED -> Emotion.LOVE;
            case INTERACTION_SHY -> Emotion.EMBARRASSMENT;
            case HURT_BY_OWNER, LONELY, IGNORED, SLEEP_DECLINED, REQUEST_FAILED, INTERACTION_REFUSED -> Emotion.SADNESS;
            case TIRED, EXHAUSTED, BEDTIME -> Emotion.TIREDNESS;
            case CYCLE_DISCOMFORT -> Emotion.DISCOMFORT;
            case HUNGRY, STARVING -> Emotion.DISCOMFORT;
            default -> Emotion.NONE;
        };
    }

    private static Emotion emotionFor(Intent i) {
        return switch (i) {
            case LOVE, MISS_YOU -> Emotion.LOVE;
            case COMPLIMENT -> Emotion.EMBARRASSMENT;
            case INSULT -> Emotion.SADNESS;
            case JOKE, GREETING, THANKS, PROMISE, PROMISE_KEPT, YES -> Emotion.JOY;
            case APOLOGY -> Emotion.RELIEF;
            default -> Emotion.NONE;
        };
    }
}
